/**
 * Rebuild the exact fixture-rig hero art as standalone SVGs. Run after changing
 * the fixture renderer, a venue name, or the venue heading line-break rule.
 * The image keeps thousands of decorative fixtures out of the page DOM and RSC.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const require = createRequire(import.meta.url);
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function loadTypeScript(relativePath) {
  const source = fs.readFileSync(path.join(root, relativePath), "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      jsx: ts.JsxEmit.ReactJSX,
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
    fileName: relativePath,
  });
  const compiledModule = { exports: {} };
  const styles = { heading: "heading", rig: "rig", fixtureLine: "fixtureLine", fixture: "fixture", illumination: "illumination", starburst: "starburst", semanticText: "semanticText" };
  const localRequire = (specifier) => specifier.endsWith(".module.css")
    ? { default: styles, ...styles }
    : require(specifier);
  new Function("require", "module", "exports", outputText)(localRequire, compiledModule, compiledModule.exports);
  return compiledModule.exports;
}

const { ACTIVE_VENUE_PAGES } = loadTypeScript("src/config/venue-pages.ts");
const { venueHeadingLines } = loadTypeScript("src/lib/venue-heading-lines.ts");
const { FixtureLensHeading } = loadTypeScript("src/components/fixture-lens-heading.tsx");
const outputDir = path.join(root, "public/images/venue-heading");
const checkOnly = process.argv.includes("--check");
if (!checkOnly) fs.mkdirSync(outputDir, { recursive: true });

function writeOrCheck(filePath, contents) {
  if (checkOnly) {
    if (!fs.existsSync(filePath) || fs.readFileSync(filePath, "utf8") !== contents) {
      throw new Error(`Stale venue heading artwork: ${path.relative(root, filePath)}. Run node scripts/generate-venue-heading-art.mjs.`);
    }
  } else {
    fs.writeFileSync(filePath, contents);
  }
}

const art = {};
for (const venue of ACTIVE_VENUE_PAGES) {
  const html = renderToStaticMarkup(React.createElement(FixtureLensHeading, {
    text: `The room: ${venue.name}.`,
    lines: venueHeadingLines(venue.name),
  }));
  const svg = html.match(/<svg\b[\s\S]*?<\/svg>/)?.[0];
  const viewBox = svg?.match(/viewBox="([^"]+)"/)?.[1];
  if (!svg || !viewBox) throw new Error(`Missing fixture art for ${venue.slug}`);
  const [, , rawWidth, rawHeight] = viewBox.split(" ").map(Number);
  const width = Number(rawWidth.toFixed(3));
  const height = Number(rawHeight.toFixed(3));
  if (!(width > 0 && height > 0)) throw new Error(`Invalid fixture dimensions for ${venue.slug}`);

  const standalone = svg
    .replace("<svg ", `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" shape-rendering="geometricPrecision" overflow="visible" `)
    .replace(/ class="(?:rig|fixtureLine|fixture|illumination)"/g, "")
    .replace(/ class="starburst"/g, ' opacity=".92"')
    .replace(/<use /g, '<use overflow="visible" ');
  const filename = `${venue.slug}.svg`;
  writeOrCheck(path.join(outputDir, filename), `${standalone}\n`);
  art[venue.slug] = { src: `/images/venue-heading/${filename}`, width, height };
}

const entries = Object.entries(art).map(([slug, value]) => (
  `  ${JSON.stringify(slug)}: ${JSON.stringify(value)},`
)).join("\n");
writeOrCheck(path.join(root, "src/config/venue-heading-art.ts"),
  `/** Generated by scripts/generate-venue-heading-art.mjs. */\nexport const VENUE_HEADING_ART = {\n${entries}\n} as const;\n`);
console.log(`${checkOnly ? "Verified" : "Generated"} ${Object.keys(art).length} venue headline SVGs.`);
